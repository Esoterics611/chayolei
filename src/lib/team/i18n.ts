export const DICTS: Record<Locale, Dict> = { en, he };

// In right-to-left text every interpolated value (a name, an amount, a version)
// is a bidi isolate, so Latin and numbers inside Hebrew sentences keep their order.
const FSI = '\u2068';
const PDI = '\u2069';

export function t(key: string, vars: Record<string, string | number> = {}): string {
  const s = DICTS[ui.locale][key] ?? en[key] ?? key;
  const isolate = ui.locale === 'he';
  // A version marker before a value ("v{n}") or a percent sign after it ("{n}%")
  // is isolated together with it.
  return s.replace(/(v?)\{(\w+)\}(%?)/g, (_, v: string, k: string, pct: string) =>
    k in vars ? (isolate ? `${FSI}${v}${vars[k]}${pct}${PDI}` : `${v}${vars[k]}${pct}`) : `${v}{${k}}${pct}`);
}

/** Render bilingual seed text, or a plain string as typed. */
export function lt(text: Text | undefined): string {
  if (text === undefined) return '';
  return typeof text === 'string' ? text : text[ui.locale];
}

const nf = (l: Locale) => new Intl.NumberFormat(l === 'he' ? 'he-IL' : 'en-US');
const intl = (l: Locale) => (l === 'he' ? 'he-IL' : 'en-US');

export const fmtNum = (n: number) => nf(ui.locale).format(n);
export const fmtTmim = (n: number) => `${nf(ui.locale).format(n)} TMIM`;

export function fmtDate(iso: string, opts: { withYear?: boolean } = {}): string {
  const d = new Date(iso);
  const sameYear = d.getFullYear() === new Date().getFullYear();
  return new Intl.DateTimeFormat(intl(ui.locale), {
    day: 'numeric', month: 'short', ...(opts.withYear || !sameYear ? { year: 'numeric' } : {}),
  }).format(d);
}

export const fmtTime = (iso: string) =>
  new Intl.DateTimeFormat(intl(ui.locale), { hour: '2-digit', minute: '2-digit' }).format(new Date(iso));

export const fmtMonth = (yyyyMm: string) =>
  new Intl.DateTimeFormat(intl(ui.locale), { month: 'long', year: 'numeric' }).format(new Date(`${yyyyMm}-15T12:00:00Z`));

/** "2 days ago", "in 26 hours", "yesterday". */
export function fmtRelative(iso: string, now = new Date().toISOString()): string {
  const diff = (new Date(iso).getTime() - new Date(now).getTime()) / 1000;
  const rtf = new Intl.RelativeTimeFormat(intl(ui.locale), { numeric: 'auto' });
  const abs = Math.abs(diff);
  if (abs < 60) return rtf.format(Math.round(diff), 'second');
  if (abs < 3600) return rtf.format(Math.round(diff / 60), 'minute');
  if (abs < 86400) return rtf.format(Math.round(diff / 3600), 'hour');
  if (abs < 86400 * 14) return rtf.format(Math.round(diff / 86400), 'day');
  return fmtDate(iso);
}

export function fmtDay(day: string): string {
  const today = new Date();
  const key = (d: Date) => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
  if (day === key(today)) return t('ledger.today');
  const y = new Date(today.getTime() - 86_400_000);
  if (day === key(y)) return t('ledger.yesterday');
  return new Intl.DateTimeFormat(intl(ui.locale), { weekday: 'long', day: 'numeric', month: 'long' }).format(new Date(`${day}T12:00:00`));
}
